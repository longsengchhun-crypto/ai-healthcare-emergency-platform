package com.healthresponse.platform.ai;

import com.healthresponse.platform.ai.TriageEngine.Result;
import com.healthresponse.platform.common.ApiException;
import com.healthresponse.platform.common.AuditService;
import com.healthresponse.platform.common.Sql;
import com.healthresponse.platform.record.RecordService;
import com.healthresponse.platform.record.RecordService.RecordView;
import com.healthresponse.platform.security.AppProperties;
import com.healthresponse.platform.security.AuthPrincipal;
import java.nio.charset.StandardCharsets;
import java.time.Instant;
import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;
import java.util.UUID;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.stereotype.Service;
import org.springframework.web.multipart.MultipartFile;

/**
 * AI features behind a provider boundary. The only provider shipped is the deterministic, rule-based
 * "deterministic-demo" provider: it is NOT a language model and every response says so. Configure
 * AI_PROVIDER to a real provider only after implementing {@link #requireProvider()} for it.
 * Inputs/outputs are validated, and only metadata (never text) is persisted.
 */
@Service
public class AiService {
    public static final String PROVIDER = "deterministic-demo";
    private static final String NOTICE =
            "AI-assisted, informational and possibly incomplete. Generated by a deterministic demonstration provider "
            + "(not a language model). Verify with a qualified clinician.";

    public record SourceRef(UUID recordId, String title) {}
    public record SummaryResult(String summary, List<String> recordedConditions, List<String> medications,
                                List<String> allergies, List<String> datesMentioned, List<String> discussWithClinician,
                                List<SourceRef> sources, String provider, boolean languageModel, String notice) {}
    public record ExtractedField(String name, String value, String evidence, double confidence) {}
    public record ExtractionResult(String documentType, List<ExtractedField> fields, String provider,
                                   boolean languageModel, String notice) {}

    private static final Pattern DATE = Pattern.compile("\\b(\\d{4}-\\d{2}-\\d{2}|\\d{1,2}/\\d{1,2}/\\d{4})\\b");
    private static final Pattern MED = Pattern.compile("(?im)^\\s*(?:medications?|rx|prescribed|drug)\\s*[:\\-]\\s*(.+)$");
    private static final Pattern ALLERGY = Pattern.compile("(?im)^\\s*allerg(?:y|ies)\\s*[:\\-]\\s*(.+)$");
    private static final Pattern CONDITION = Pattern.compile("(?im)^\\s*(?:diagnosis|conditions?|history|problem)\\s*[:\\-]\\s*(.+)$");
    private static final Pattern VALUE = Pattern.compile(
            "(?im)^\\s*([A-Za-z][A-Za-z /()%-]{2,40})\\s*[:=]\\s*(\\d+(?:\\.\\d+)?\\s*[A-Za-z/%µ^0-9]*)\\s*$");

    private final RecordService records;
    private final TriageEngine triage;
    private final AuditService audit;
    private final JdbcClient jdbc;
    private final AppProperties props;

    public AiService(RecordService records, TriageEngine triage, AuditService audit, JdbcClient jdbc, AppProperties props) {
        this.records = records;
        this.triage = triage;
        this.audit = audit;
        this.jdbc = jdbc;
        this.props = props;
    }

    private void requireProvider() {
        if (!PROVIDER.equals(props.ai().provider())) {
            throw new ApiException(HttpStatus.SERVICE_UNAVAILABLE, "AI_PROVIDER_NOT_CONFIGURED",
                    "The configured AI provider is not available. Please try again later.");
        }
    }

    // ---- triage (always deterministic; never delayed by any model call)
    public Result triage(AuthPrincipal p, String symptoms) {
        Instant t0 = Instant.now();
        Result r = triage.assess(symptoms);
        log(p, "TRIAGE", "OK", t0);
        audit.ok(p, "AI_TRIAGE", "AI", null);
        return r;
    }

    // ---- summary
    public SummaryResult summarize(AuthPrincipal p, UUID patientId) {
        requireProvider();
        Instant t0 = Instant.now();
        List<RecordView> recs = records.list(p, patientId); // enforces authorization + audit
        Set<String> meds = new LinkedHashSet<>(), allergies = new LinkedHashSet<>(), conds = new LinkedHashSet<>(),
                dates = new LinkedHashSet<>();
        List<SourceRef> sources = new ArrayList<>();
        for (RecordView r : recs) {
            String text = r.body() == null ? "" : r.body();
            int before = meds.size() + allergies.size() + conds.size() + dates.size();
            collect(MED, text, meds);
            collect(ALLERGY, text, allergies);
            collect(CONDITION, text, conds);
            Matcher d = DATE.matcher(text);
            while (d.find()) dates.add(d.group(1));
            if (meds.size() + allergies.size() + conds.size() + dates.size() > before || !text.isBlank()) {
                sources.add(new SourceRef(r.id(), r.title()));
            }
        }
        String summary = recs.isEmpty()
                ? "No medical records are available to summarise."
                : "Found %d record(s). Recorded conditions: %d, medication entries: %d, allergy entries: %d. "
                        .formatted(recs.size(), conds.size(), meds.size(), allergies.size())
                        + "Only facts that appear verbatim in the records are listed; nothing was inferred.";
        log(p, "SUMMARY", "OK", t0);
        return new SummaryResult(summary, List.copyOf(conds), List.copyOf(meds), List.copyOf(allergies),
                List.copyOf(dates), List.of("Review this summary and the source records with your clinician."),
                sources, PROVIDER, false, NOTICE);
    }

    private void collect(Pattern pat, String text, Set<String> out) {
        Matcher m = pat.matcher(text);
        while (m.find()) out.add(m.group(1).trim());
    }

    // ---- document extraction (plain-text documents only; no OCR provider is configured)
    public ExtractionResult extract(AuthPrincipal p, MultipartFile file) {
        requireProvider();
        Instant t0 = Instant.now();
        if (file == null || file.isEmpty()) throw ApiException.badRequest("EMPTY_FILE", "No file was provided");
        if (file.getSize() > 1_000_000) throw ApiException.badRequest("FILE_TOO_LARGE", "Text documents are limited to 1 MB");
        String ct = file.getContentType() == null ? "" : file.getContentType();
        if (!ct.startsWith("text/plain")) {
            log(p, "EXTRACTION", "UNSUPPORTED", t0);
            throw new ApiException(HttpStatus.UNPROCESSABLE_ENTITY, "OCR_NOT_CONFIGURED",
                    "Image/PDF extraction needs an OCR provider, which is not configured. Upload a plain-text document.");
        }
        String text;
        try {
            text = new String(file.getBytes(), StandardCharsets.UTF_8);
        } catch (java.io.IOException e) {
            throw ApiException.badRequest("UNREADABLE", "The file could not be read");
        }
        List<ExtractedField> fields = new ArrayList<>();
        Matcher m = MED.matcher(text);
        while (m.find()) fields.add(new ExtractedField("medication", m.group(1).trim(), m.group(0).trim(), 0.9));
        m = ALLERGY.matcher(text);
        while (m.find()) fields.add(new ExtractedField("allergy", m.group(1).trim(), m.group(0).trim(), 0.9));
        m = DATE.matcher(text);
        while (m.find()) fields.add(new ExtractedField("date", m.group(1), m.group(0), 0.95));
        m = VALUE.matcher(text);
        while (m.find()) fields.add(new ExtractedField("reportedValue:" + m.group(1).trim(), m.group(2).trim(), m.group(0).trim(), 0.8));
        String type = text.toLowerCase().contains("discharge") ? "DISCHARGE_SUMMARY"
                : (text.toLowerCase().contains("lab") || text.toLowerCase().contains("result")) ? "TEST_REPORT" : "UNKNOWN";
        log(p, "EXTRACTION", "OK", t0);
        audit.ok(p, "AI_EXTRACTION", "AI", null);
        return new ExtractionResult(type, fields, PROVIDER, false,
                NOTICE + " Extracted values are not clinically validated.");
    }

    private void log(AuthPrincipal p, String feature, String status, Instant t0) {
        jdbc.sql("""
                INSERT INTO ai_processing_records (id, user_id, feature, provider, status, latency_ms, created_at)
                VALUES (:id, :u, :f, :p, :s, :l, :now)""")
                .param("id", UUID.randomUUID()).param("u", p.userId()).param("f", feature).param("p", PROVIDER)
                .param("s", status).param("l", Instant.now().toEpochMilli() - t0.toEpochMilli())
                .param("now", Sql.ts(Instant.now())).update();
    }
}
